"""
Strict SQL AST security validator.

Enforces read-only execution constraints, prohibits DDL/DML mutations,
restricts analytical functions to a strict allowlist, and blocks catalog probing.
"""
from typing import Set

import sqlglot
from sqlglot import exp

from enterprise_ai_platform.core.exceptions import SqlSecurityError

# Whitelist of approved analytical and scalar functions for Text-to-SQL
ALLOWED_FUNCTIONS: Set[str] = {
    # Aggregation
    "count",
    "sum",
    "avg",
    "min",
    "max",
    # Null & Type handling
    "coalesce",
    "nullif",
    "cast",
    # Numeric
    "round",
    "abs",
    "ceil",
    "ceiling",
    "floor",
    "trunc",
    # String manipulation
    "lower",
    "upper",
    "trim",
    "ltrim",
    "rtrim",
    "concat",
    "substring",
    "length",
    "replace",
    # Date & Time
    "date_trunc",
    "extract",
    "now",
    "current_date",
    "current_timestamp",
    "date_part",
    "age",
}

# Forbidden metadata, execution, or penetration testing functions
PROHIBITED_FUNCTIONS: Set[str] = {
    "pg_sleep",
    "pg_read_file",
    "pg_ls_dir",
    "pg_stat_file",
    "current_user",
    "currentuser",
    "session_user",
    "sessionuser",
    "version",
    "currentversion",
    "current_database",
    "currentdatabase",
    "current_schema",
    "currentschema",
    "eval",
    "exec",
    "load_file",
    "dblink",
    "query_to_xml",
}

# Forbidden system schemas
PROHIBITED_SCHEMAS: Set[str] = {
    "pg_catalog",
    "information_schema",
    "pg_toast",
}


class SqlAstValidator:
    """
    Validates SQL queries against strict read-only and analytical safety constraints.
    """

    def validate_sql(self, sql_string: str) -> exp.Expression:
        """
        Parse and validate raw SQL string for single-statement read-only execution.

        Args:
            sql_string: Input SQL string generated by LLM.

        Returns:
            Validated sqlglot AST expression.

        Raises:
            SqlSecurityError: If query is empty, multiple statements, mutating, or insecure.
        """
        if not sql_string or not sql_string.strip():
            raise SqlSecurityError("SQL query string cannot be empty.")

        clean_sql = sql_string.strip()

        # 1. Parse SQL statements - prohibit multi-statement execution (semicolon injection)
        try:
            parsed_statements = sqlglot.parse(clean_sql, read="postgres")
        except Exception as e:
            raise SqlSecurityError(f"SQL syntax error: {str(e)}") from e

        if not parsed_statements or parsed_statements[0] is None:
            raise SqlSecurityError("Failed to parse valid SQL statement.")

        if len(parsed_statements) > 1:
            raise SqlSecurityError(
                "Multiple SQL statements detected (semicolon injection). Only a single SELECT query is permitted."
            )

        ast = parsed_statements[0]
        self.validate_ast(ast)
        return ast

    def validate_ast(self, ast: exp.Expression) -> None:
        """
        Validate parsed AST node against security invariants.

        Enforces:
            1. Query root is a read-only SELECT (or WITH CTE / UNION of SELECTs).
            2. No DDL/DML statements (INSERT, UPDATE, DELETE, DROP, ALTER, CREATE, TRUNCATE).
            3. No system catalog references (pg_catalog, information_schema).
            4. Functions are strictly limited to ALLOWED_FUNCTIONS.

        Args:
            ast: Parsed SQLGlot AST node.

        Raises:
            SqlSecurityError: If any security invariant is violated.
        """
        # 1. Check for mutating statements
        if isinstance(
            ast,
            (
                exp.Insert,
                exp.Update,
                exp.Delete,
                exp.Drop,
                exp.Alter,
                exp.Create,
                exp.Command,
                exp.Transaction,
                exp.Commit,
                exp.Rollback,
                exp.Pragma,
            ),
        ):
            raise SqlSecurityError(
                f"Mutating or administrative SQL statement of type '{type(ast).__name__}' is strictly forbidden."
            )

        # 2. Must be a Select query (or Union / Expression with Select)
        if not isinstance(ast, (exp.Select, exp.Union)):
            raise SqlSecurityError(
                f"Query must be a SELECT statement, received '{type(ast).__name__}'."
            )

        # 3. Disallow subquery mutations (e.g. SELECT * FROM (INSERT ...))
        mutating_nodes = list(
            ast.find_all(
                (
                    exp.Insert,
                    exp.Update,
                    exp.Delete,
                    exp.Drop,
                    exp.Alter,
                    exp.Create,
                )
            )
        )
        if mutating_nodes:
            raise SqlSecurityError("Mutating operations within nested expressions are forbidden.")

        # 4. Check for system catalog schemas
        for table in ast.find_all(exp.Table):
            db = table.db
            if db and db.strip().lower() in PROHIBITED_SCHEMAS:
                raise SqlSecurityError(
                    f"Direct access to system schema '{db}' is forbidden."
                )

        # 5. Check all function calls against allowlist (excluding binary/logical operators)
        for func in ast.find_all(exp.Func):
            if isinstance(func, (exp.Binary, exp.Connector, exp.Predicate)):
                continue

            func_name = (func.name if isinstance(func, exp.Anonymous) else func.key).strip().lower()

            if func_name in PROHIBITED_FUNCTIONS:
                raise SqlSecurityError(
                    f"Function '{func_name}' is forbidden for security reasons."
                )

            if func_name not in ALLOWED_FUNCTIONS:
                raise SqlSecurityError(
                    f"Custom or non-whitelisted analytical function '{func_name}' is forbidden."
                )
